INSERT INTO dbo.CountryMaster (CountryName, CountryCode, Iso2Code, Iso3Code, EnteredBy, EnteredDate, DeleteStatus)
SELECT l.CountryName, l.CountryCode, l.Iso2Code, l.Iso3Code, l.EnteredBy, l.EnteredDate, l.DeleteStatus
FROM #CountryLoad l
WHERE NOT EXISTS (
    SELECT 1 FROM dbo.CountryMaster c
    WHERE c.CountryName = l.CountryName AND ISNULL(c.DeleteStatus, 0) = 0
);

UPDATE c
SET
    c.Iso2Code = CASE WHEN c.Iso2Code IS NULL OR LTRIM(RTRIM(c.Iso2Code)) = N'' THEN l.Iso2Code ELSE c.Iso2Code END,
    c.Iso3Code = CASE WHEN c.Iso3Code IS NULL OR LTRIM(RTRIM(c.Iso3Code)) = N'' THEN l.Iso3Code ELSE c.Iso3Code END
FROM dbo.CountryMaster c
INNER JOIN #CountryLoad l ON l.CountryName = c.CountryName
WHERE ISNULL(c.DeleteStatus, 0) = 0
  AND (
        c.Iso2Code IS NULL OR LTRIM(RTRIM(c.Iso2Code)) = N''
        OR c.Iso3Code IS NULL OR LTRIM(RTRIM(c.Iso3Code)) = N''
      );

DROP TABLE #CountryLoad;

SELECT c.CountryId, c.CountryName, c.CountryCode, c.Iso2Code, c.Iso3Code
FROM dbo.CountryMaster c
WHERE ISNULL(c.DeleteStatus, 0) = 0
  AND c.CountryName <> N'Other'
  AND (c.Iso2Code IS NULL OR LTRIM(RTRIM(c.Iso2Code)) = N''
       OR c.Iso3Code IS NULL OR LTRIM(RTRIM(c.Iso3Code)) = N'')
ORDER BY c.CountryName;
